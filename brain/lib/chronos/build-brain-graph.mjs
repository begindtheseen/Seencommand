// Inline brain/lib/chronos/layout.mjs into lib/ui/brain-graph.js.
//
// The dashboard inlines lib/ui/*.js as plain <script> text, so the browser component cannot import an
// ES module. Instead the layout logic is copied, verbatim minus the `export` keywords, between the
// BEGIN/END markers of brain-graph.js. Run after every change to layout.mjs:
//
//   node brain/lib/chronos/build-brain-graph.mjs          (rewrites the block)
//   node brain/lib/chronos/build-brain-graph.mjs --check  (exit 1 if the block is out of date)
//
// layout.test.mjs runs the same check, so a stale copy fails the test suite.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
export const LAYOUT_PATH = join(HERE, 'layout.mjs');
export const BROWSER_PATH = join(HERE, '..', '..', '..', 'lib', 'ui', 'brain-graph.js');
export const BEGIN = '// ==== BEGIN layout.mjs (generated by brain/lib/chronos/build-brain-graph.mjs — do not edit here) ====';
export const END = '// ==== END layout.mjs ====';

// layout.mjs → browser text: drop `export ` in front of top-level declarations. Anything that cannot
// run inside a classic script (an import, an `export default`, `export {…}`) is refused.
export function transformLayoutSource(src) {
  const lines = String(src).replace(/\r\n/g, '\n').split('\n');
  return lines.map((line, i) => {
    if (/^\s*import\b/.test(line) || /^\s*export\s+(default|\{|\*)/.test(line)) {
      throw new Error(`layout.mjs:${i + 1} cannot be inlined into a classic script: ${line.trim()}`);
    }
    return line.replace(/^export (function|const|let|class) /, '$1 ');
  }).join('\n').trimEnd();
}

// The block currently inlined in brain-graph.js (between the markers), or null if the markers are missing.
export function extractInlined(browserSrc) {
  const s = String(browserSrc);
  const a = s.indexOf(BEGIN), b = s.indexOf(END);
  if (a < 0 || b < 0 || b < a) return null;
  return s.slice(a + BEGIN.length, b).replace(/^\n/, '').trimEnd();
}

export function inline(browserSrc, layoutSrc) {
  const s = String(browserSrc);
  const a = s.indexOf(BEGIN), b = s.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error('brain-graph.js is missing its BEGIN/END layout markers');
  return `${s.slice(0, a + BEGIN.length)}\n${transformLayoutSource(layoutSrc)}\n${s.slice(b)}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const layoutSrc = readFileSync(LAYOUT_PATH, 'utf8');
  const browserSrc = readFileSync(BROWSER_PATH, 'utf8');
  const fresh = extractInlined(browserSrc) === transformLayoutSource(layoutSrc);
  if (process.argv.includes('--check')) {
    if (!fresh) { console.error('lib/ui/brain-graph.js is out of date — run node brain/lib/chronos/build-brain-graph.mjs'); process.exit(1); }
    console.log('lib/ui/brain-graph.js layout block is current');
  } else if (fresh) {
    console.log('lib/ui/brain-graph.js already current');
  } else {
    writeFileSync(BROWSER_PATH, inline(browserSrc, layoutSrc));
    console.log('lib/ui/brain-graph.js layout block rebuilt');
  }
}
