export const ACT_VERBS = ACT_GROUPS.flatMap((g) => g.verbs.map(([name, args, what]) => ({ name, args, what, group: g.id })));

/** One line per group: "• Title: verb args — what · verb …" (the chat prompt's verb list). */
export function catalogLines() {
  return ACT_GROUPS.map((g) => `• ${g.title}: ${g.verbs.map(([n, a, w]) => `\`${n}${a ? ` ${a}` : ''}\` ${w}`).join(' · ')}`).join('\n');
}
